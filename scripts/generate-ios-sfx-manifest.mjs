import { access, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const iosDir = path.join(repoRoot, "public", "sounds", "ios");
const outputPath = path.join(
  repoRoot,
  "lib",
  "entrance",
  "generated-ios-sfx-manifest.ts",
);

/** glassSlide は grass.mp4 として配置 */
const IOS_SFX_FILES = {
  click: "click.mp4",
  door: "door.mp4",
  glassSlide: "grass.mp4",
};

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function readIosSfxManifest() {
  const manifest = {};

  for (const [kind, fileName] of Object.entries(IOS_SFX_FILES)) {
    const filePath = path.join(iosDir, fileName);
    manifest[kind] = await fileExists(filePath);
  }

  return manifest;
}

function renderManifest(manifest) {
  const lines = Object.entries(manifest).map(
    ([kind, available]) => `  ${kind}: ${available},`,
  );

  return `/**
 * Auto-generated by scripts/generate-ios-sfx-manifest.mjs
 * Do not edit manually.
 */
export const IOS_SFX_FILE_AVAILABLE = {
${lines.join("\n")}
} as const satisfies Record<"click" | "door" | "glassSlide", boolean>;
`;
}

async function main() {
  await mkdir(iosDir, { recursive: true });
  const manifest = await readIosSfxManifest();
  await writeFile(outputPath, renderManifest(manifest), "utf8");
  console.info("[ios-sfx-manifest]", manifest);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
