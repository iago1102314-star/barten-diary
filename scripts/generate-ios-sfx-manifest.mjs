import { access, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const iosDir = path.join(repoRoot, "public", "sounds", "ios");
const outputPath = path.join(
  repoRoot,
  "lib",
  "entrance",
  "generated-ios-sfx-manifest.ts",
);

/** glassSlide は grass.mp4 として配置 */
const IOS_SFX_FILES = {
  click: "click.mp4",
  door: "door.mp4",
  glassSlide: "grass.mp4",
  send: "send.mp4",
  menuOpen: "menu-open.mp4",
  menuClick: "menu-click.mp4",
  page: "page.mp4",
  think: "think.mp4",
};

const IOS_SFX_KIND_UNION = Object.keys(IOS_SFX_FILES)
  .map((kind) => `"${kind}"`)
  .join(" | ");

async function readCurrentRevision() {
  try {
    const content = await readFile(outputPath, "utf8");
    const match = content.match(/IOS_SFX_CACHE_REVISION = (\d+)/);
    return match ? Number.parseInt(match[1], 10) : 0;
  } catch {
    return 0;
  }
}

async function iosFilesNewerThanManifest(manifestMtimeMs) {
  for (const fileName of Object.values(IOS_SFX_FILES)) {
    const filePath = path.join(iosDir, fileName);
    const fileStat = await stat(filePath).catch(() => null);
    if (fileStat && fileStat.mtimeMs > manifestMtimeMs) {
      return true;
    }
  }
  return false;
}

async function readIosSfxManifest() {
  const availability = {};
  const byteLength = {};
  const lastModified = {};

  for (const [kind, fileName] of Object.entries(IOS_SFX_FILES)) {
    const filePath = path.join(iosDir, fileName);
    const fileStat = await stat(filePath).catch(() => null);
    availability[kind] = Boolean(fileStat?.isFile());
    byteLength[kind] = fileStat?.size ?? 0;
    lastModified[kind] = fileStat ? fileStat.mtime.toISOString() : null;
  }

  return { availability, byteLength, lastModified };
}

function renderRecord(entries) {
  return Object.entries(entries)
    .map(([key, value]) => {
      if (value === null) {
        return `  ${key}: null,`;
      }
      if (typeof value === "string") {
        return `  ${key}: ${JSON.stringify(value)},`;
      }
      if (typeof value === "boolean") {
        return `  ${key}: ${value},`;
      }
      return `  ${key}: ${value},`;
    })
    .join("\n");
}

function renderManifest(manifest, revision) {
  return `/**
 * Auto-generated by scripts/generate-ios-sfx-manifest.mjs
 * Do not edit manually.
 */
/** Safari / HTMLAudioElement pool — ios 音源再生成時に bump する */
export const IOS_SFX_CACHE_REVISION = ${revision};

export const IOS_SFX_FILE_AVAILABLE = {
${renderRecord(manifest.availability)}
} as const satisfies Record<${IOS_SFX_KIND_UNION}, boolean>;

/** ビルド時の実ファイルサイズ — SE3 fetch 証明ログと照合 */
export const IOS_SFX_FILE_BYTE_LENGTH = {
${renderRecord(manifest.byteLength)}
} as const satisfies Record<${IOS_SFX_KIND_UNION}, number>;

/** ビルド時の mtime（ISO） — Last-Modified 照合用 */
export const IOS_SFX_FILE_LAST_MODIFIED = {
${renderRecord(manifest.lastModified)}
} as const satisfies Record<${IOS_SFX_KIND_UNION}, string | null>;
`;
}

async function main() {
  const bump = process.argv.includes("--bump");
  await mkdir(iosDir, { recursive: true });

  const manifest = await readIosSfxManifest();
  let revision = await readCurrentRevision();
  if (revision < 1) revision = 1;

  const manifestStat = await stat(outputPath).catch(() => null);
  const shouldAutoBump =
    !bump &&
    manifestStat &&
    (await iosFilesNewerThanManifest(manifestStat.mtimeMs));

  if (bump || shouldAutoBump) {
    revision += 1;
  }

  await writeFile(outputPath, renderManifest(manifest, revision), "utf8");
  console.info("[ios-sfx-manifest]", {
    revision,
    bumped: bump || shouldAutoBump,
    availability: manifest.availability,
    byteLength: manifest.byteLength,
  });
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
