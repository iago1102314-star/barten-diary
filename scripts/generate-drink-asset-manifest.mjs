import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const drinksDir = path.join(repoRoot, "public", "assets", "drinks");
const outputPath = path.join(
  repoRoot,
  "lib",
  "drinks",
  "generated-drink-asset-manifest.ts",
);

const IMAGE_FILE_PATTERN = /^(\d+)\.webp$/i;

async function readDrinkManifest() {
  const manifest = {};
  const drinkIds = await readdir(drinksDir).catch(() => []);

  for (const drinkId of drinkIds) {
    const drinkDir = path.join(drinksDir, drinkId);
    const drinkStat = await stat(drinkDir).catch(() => null);
    if (!drinkStat?.isDirectory()) continue;

    const diaryDir = path.join(drinkDir, "diary");
    const diaryFiles = await readdir(diaryDir).catch(() => []);
    const diaryIndices = diaryFiles
      .map((fileName) => {
        const match = fileName.match(IMAGE_FILE_PATTERN);
        return match ? Number.parseInt(match[1], 10) : null;
      })
      .filter((value) => value !== null)
      .sort((a, b) => a - b);

    const recordPath = path.join(drinkDir, "record.webp");
    const hasRecord = Boolean(await stat(recordPath).catch(() => null));

    manifest[drinkId] = {
      diaryIndices,
      hasRecord,
    };
  }

  return manifest;
}

function renderManifest(manifest) {
  return `/**
 * Auto-generated by scripts/generate-drink-asset-manifest.mjs
 * Do not edit manually.
 */

export const GENERATED_DRINK_ASSET_MANIFEST = ${JSON.stringify(
    manifest,
    null,
    2,
  )} as const;
`;
}

await mkdir(path.dirname(outputPath), { recursive: true });
const manifest = await readDrinkManifest();
await writeFile(outputPath, renderManifest(manifest), "utf8");
console.log(`Generated drink asset manifest: ${outputPath}`);
